/**
 * Question Generator Function
 * Guarantees exact count (10, 20, 25, 30, 40)
 * Strictly belongs to the current Unit
 * Guarantees varied questions with ZERO duplicate or near-duplicate questions
 * Enforces controlled variation across names, subjects, objects, and situations
 * Validates every question before returning it to the user
 */
export const generateQuestionSession = (
  unitId: string,
  difficulty: DifficultyLevelId,
  count: QuestionPackageCount
): QuizQuestion[] => {
  let seedPool: QuizQuestion[] | undefined;

  // For GS1-U01, provide the verified blueprints as seed candidates
  if (unitId === 'GS1-U01') {
    if (difficulty === 'level1') {
      seedPool = [...RAW_QUESTIONS_LEVEL_1, ...RAW_QUESTIONS_LEVEL_2, ...RAW_QUESTIONS_LEVEL_3];
    } else if (difficulty === 'level2') {
      seedPool = [...RAW_QUESTIONS_LEVEL_2, ...RAW_QUESTIONS_LEVEL_1, ...RAW_QUESTIONS_LEVEL_3];
    } else {
      seedPool = [...RAW_QUESTIONS_LEVEL_3, ...RAW_QUESTIONS_LEVEL_2, ...RAW_QUESTIONS_LEVEL_1];
    }
  }

  const initialQuestions = generateQuestionsForProfile(unitId, difficulty, count, seedPool);

  // Mandatory Golden Rules: Run strict Grammar & Meaning Validation on EVERY question
  // If ANY question fails, automatically REGENERATE it before showing to the student.
  const verifiedQuestions: QuizQuestion[] = [];
  for (let i = 0; i < initialQuestions.length; i++) {
    const q = initialQuestions[i];
    const verifiedQ = auditAndRegenerateQuestion(q, unitId, difficulty, verifiedQuestions, i + 1);
    verifiedQuestions.push(verifiedQ);
  }

  return verifiedQuestions;
};
